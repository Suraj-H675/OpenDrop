/// Future platform implementation must use the real Android Keystore, Windows
/// CNG, or an appropriately secured Linux key store. No fallback software key
/// is silently generated by the shared domain layer.
pub trait DeviceKeySigner: Send + Sync {
    fn public_key_der(&self) -> Result<Vec<u8>, String>;
    fn sign_challenge(&self, challenge: &[u8]) -> Result<Vec<u8>, String>;
}

/// A single received file name, NEVER a path. The native destination adapter
/// handles normalization, collisions and user-granted destination capability.
pub fn validate_file_name(name: &str) -> Result<(), Error> {
    if name.is_empty()
        || name.len() > 255
        || name == "."
        || name == ".."
        || name.starts_with('.')
        || name.ends_with(' ')
        || name.ends_with('.')
        || name.contains('/')
        || name.contains('\\')
        || name.contains(':')
        || name.chars().any(char::is_control)
    {
        return Err(Error::Invalid("file name"));
    }
    let first = name.split('.').next().unwrap_or("").to_ascii_uppercase();
    if matches!(
        first.as_str(),
        "CON"
            | "PRN"
            | "AUX"
            | "NUL"
            | "COM1"
            | "COM2"
            | "COM3"
            | "COM4"
            | "COM5"
            | "COM6"
            | "COM7"
            | "COM8"
            | "COM9"
            | "LPT1"
            | "LPT2"
            | "LPT3"
            | "LPT4"
            | "LPT5"
            | "LPT6"
            | "LPT7"
            | "LPT8"
            | "LPT9"
    ) {
        return Err(Error::Invalid("platform-reserved file name"));
    }
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn typed_ids_cannot_confuse_names_or_display_strings() {
        assert!(DeviceId::parse("Alice's phone").is_err());
        assert!(TransferId::parse("af".repeat(16).as_str()).is_ok());
        assert!(Sha256Digest::parse(&"a".repeat(63)).is_err());
        assert_eq!(
            KeyFingerprint::parse(&"AB".repeat(32)).unwrap().as_str(),
            "ab".repeat(32)
        );
    }
    #[test]
    fn reject_untrusted_filename_components() {
        for name in [
            "", ".", "..", ".hidden", "../evil", "a\\b", "a:b", "CON.txt", "x\n.txt", "file.",
            "file ",
        ] {
            assert!(validate_file_name(name).is_err(), "{name:?}");
        }
        assert!(validate_file_name("Report_日本語.pdf").is_ok());
    }
}
